const { chromium } = require('../../../../e2e/node_modules/@playwright/test');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
(async () => {
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const output=path.resolve(__dirname,'../../../assets/screenshots/gantt');
  async function capture(name){
    let v=1;
    while(fs.existsSync(path.join(output,name+'-Ver'+v+'.png')))v++;
    await page.screenshot({path:path.join(output,name+'-Ver'+v+'.png'),fullPage:true});
  }
  try {
    await page.goto(pathToFileURL(path.join(__dirname,'option-c-ver2.html')).href);
    assert.equal(await page.title(),'Pairing Builder | Option C Ver2');
    assert.equal(await page.locator('#build').isDisabled(),true);
    await page.locator('#from').fill('2026-08-30');
    await page.locator('#find-flights').click();
    assert.match(await page.locator('#error').innerText(),/within the open Gantt/);
    await page.locator('#from').fill('2026-09-09');
    await page.locator('#find-flights').click();
    assert.equal(await page.locator('.flight-result').count(),9);
    assert.equal(await page.locator('#build').innerText(),'Build all (3)');
    await capture('pairing-builder-option-c-ver2-search');
    await page.getByRole('radio',{name:'Select EK201',exact:true}).click();
    assert.match(await page.locator('#rotation-preview').innerText(),/Layover · LHR/);
    assert.match(await page.locator('#rotation-preview').innerText(),/20:00/);
    assert.match(await page.locator('#rotation-preview').innerText(),/17:45 rest between duties/);
    assert.equal(await page.locator('#build').innerText(),'Build pairing');
    await capture('pairing-builder-option-c-ver2-layover');
    await page.getByRole('radio',{name:'Select EK302',exact:true}).click();
    assert.match(await page.locator('#rotation-preview').innerText(),/4 segments · 1 duty · No layover/);
    assert.match(await page.locator('#rotation-preview').innerText(),/Total block 04:00/);
    assert.equal(await page.locator('.segment-detail tbody tr').count(),4);
    assert.equal(await page.locator('.layover-stage').count(),0);
    await capture('pairing-builder-option-c-ver2-four-segments');
    await page.locator('#block').fill('200');
    assert.equal(await page.locator('#build').isDisabled(),true);
    await page.locator('#find-flights').click();
    await page.getByRole('radio',{name:'Select EK302',exact:true}).click();
    assert.equal(await page.locator('#build').isDisabled(),true);
    await page.locator('#block').fill('480');
    await page.locator('#find-flights').click();
    await page.getByRole('radio',{name:'Select EK209',exact:true}).click();
    assert.equal(await page.locator('#build').isDisabled(),true);
    assert.match(await page.locator('#rotation-preview').innerText(),/remain unpaired/);
    await page.getByRole('radio',{name:'Select EK302',exact:true}).click();
    await page.locator('#build').click();
    await page.locator('#overlay').waitFor({state:'hidden'});
    assert.equal(await page.locator('.newrow').count(),1);
    assert.equal(await page.locator('.newrow .puck').count(),4);
    assert.equal(await page.locator('.newrow .rest').count(),0);
    await page.locator('#open-builder').click();
    await page.locator('#find-flights').click();
    assert.equal(await page.locator('.flight-result').count(),5);
    assert.equal(await page.locator('#build').innerText(),'Build all (2)');
    await page.getByRole('radio',{name:'Select EK201',exact:true}).click();
    await page.locator('#clear-flight').click();
    assert.equal(await page.locator('#build').innerText(),'Build all (2)');
    await page.locator('#build').click();
    await page.locator('#overlay').waitFor({state:'hidden'});
    assert.deepEqual(await page.locator('.newrow').evaluateAll(es=>es.map(e=>e.dataset.pairing)),['DEMO-003','DEMO-002','DEMO-001']);
    await capture('pairing-builder-option-c-ver2-results');
    await page.locator('#open-builder').click();
    await page.locator('#from').fill('2026-09-01');
    await page.locator('#to').fill('2026-09-02');
    await page.locator('#find-flights').click();
    assert.match(await page.locator('#flight-list').innerText(),/No open flights/);
    assert.equal(await page.locator('#build').isDisabled(),true);
    await page.locator('#from').fill('2026-09-09');
    await page.locator('#to').fill('2026-09-15');
    await page.locator('#base').selectOption('ADD');
    await page.locator('#fleet').selectOption('B788');
    await page.locator('#find-flights').click();
    assert.equal(await page.locator('.flight-result').count(),9);
    await page.getByRole('radio',{name:'Select ET301',exact:true}).click();
    assert.match(await page.locator('#rotation-preview').innerText(),/ADD → NBO → EBB → NBO → ADD/);
    await page.setViewportSize({width:390,height:844});
    await page.locator('#rotation-preview').scrollIntoViewIfNeeded();
    await capture('pairing-builder-option-c-ver2-mobile');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    const rect=await page.locator('.dialog').boundingBox();
    assert.ok(rect.x>=0 && rect.x+rect.width<=390 && rect.y+rect.height<=844);
    assert.deepEqual(errors,[]);
    console.log('PASS Option C Ver2: search gating/date bounds; scope filtering; layover preview; four-segment single-duty preview; block cap; unclosable flight; single build; clear selection/build all; newest-first; no duplicate reuse; empty results; mobile; screenshots; no JS errors.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
