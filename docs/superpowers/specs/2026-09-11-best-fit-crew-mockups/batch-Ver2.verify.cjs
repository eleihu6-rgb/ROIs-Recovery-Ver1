  for (const id of ['P4101-CA', 'P4102-CA']) assert.match(await page.locator(`[data-recommendation="${id}"]`).innerText(), /CA best: 21551 · CAD/);
  assert.match(await page.locator('[data-recommendation="P4101-CA"]').innerText(), /Shortlisted: 20498/);
  assert.equal(await page.locator('tbody tr').first().locator('[data-crew]').getAttribute('data-crew'), '21551');
  assert.equal(await page.locator('#find').isDisabled(), false);
  await page.screenshot({ path: path.resolve(__dirname, '../../../assets/screenshots/gantt/best-fit-batch-Ver4.png'), fullPage: true });
  await page.locator('[data-detail="22005"]').click();
  assert.match(await page.locator('.rules').innerText(), /Engine timeout/);
  await page.locator('#retry').click();
  await page.waitForFunction(() => !window.batchDemo.snapshot.running);
  assert.equal(await page.locator('[data-crew="22005"]').isDisabled(), false);
  assert.equal(await page.locator('#check').isDisabled(), false);
  assert.equal(await page.locator('[data-crew="21551"]').isChecked(), true);
  await page.locator('#costset').selectOption('premium');
  assert.match(await page.locator('.rules').innerText(), /F8 Premium · rev 2/);
