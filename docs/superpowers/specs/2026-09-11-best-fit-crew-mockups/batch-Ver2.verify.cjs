  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: batch toolbar and right-click entry, multi-pairing search, basic filter, baseline delta, blocked/unknown selection, retry, fairness/cost, shared crew conflict and alternate resolution, invalidation, mobile controls; zero page errors.');
