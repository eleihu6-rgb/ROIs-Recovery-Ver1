  assert.match(await page.locator('#detail').innerText(), /Shared recommendation/);
  assert.equal(await page.locator('[data-crew="22004"]').isDisabled(), true);
  assert.equal(await page.locator('[data-crew="22005"]').isDisabled(), true);
  assert.equal(await page.locator('[data-crew="24001"]').count(), 0);
  await page.locator('[data-crew="20498"]').check();
  assert.match(await page.locator('.rules').innerText(), /before 1 → after 1 · new 0/);
  await page.locator('[data-slot="FO"]').click();
  await page.locator('[data-crew="23001"]').check();
  await page.locator('[data-view="P4102"]').click();
