  await page.locator('[data-crew="23001"]').check();
  await page.locator('#check').click();
  assert.match(await page.locator('#combined').innerText(), /20498: P4101 \+ P4102 overlap/);
  await page.locator('[data-view="P4102"]').click();
  await page.locator('[data-crew="21551"]').check();
  assert.match(await page.locator('#combined').innerText(), /Selection changed/);
  await page.locator('#check').click();
  assert.match(await page.locator('#combined').innerText(), /Combined fixture check passed/);
  assert.match(await page.locator('#combined').innerText(), /Combined credit-payroll cost: CAD 1,697/);
