export function BrandLogo({ airline, height = 34 }: BrandLogoProps): React.JSX.Element {
  if (airline === 'TG') {
    return <ThaiLogo height={height} />;
  }
  if (airline === 'ET') {
    const etHeight = height === 34 ? 30 : height;
    const etWidth = (etHeight * 800) / 335;
    return (
      <Image
        source={ethiopianLogo}
        resizeMode="contain"
        style={{ height: etHeight, width: etWidth }}
      />
    );
  }
  if (airline === 'EK') {
    // The Emirates lockup is stacked (calligraphy over wordmark), so its aspect is
    // ~1.45:1 — keep the requested height and let the width follow.
    const ekWidth = (height * 690) / 475;
    return (
      <Image
        source={emiratesLogo}
        resizeMode="contain"
        style={{ height, width: ekWidth }}
      />
    );
  }
  return (
    <View style={styles.fallback}>
      <Icon name="jet" size={30} color="#fff" />
      <Text style={styles.fallbackText}>{airline}</Text>
    </View>
  );
}

